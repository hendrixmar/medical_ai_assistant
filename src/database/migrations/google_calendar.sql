CREATE TABLE google_connection (
  id integer PRIMARY KEY CHECK (id=1),
  deployment_marker text NOT NULL,
  status text NOT NULL DEFAULT 'disconnected' CHECK (status IN ('disconnected','connected','reauthorize')),
  generation bigint NOT NULL DEFAULT 0 CHECK (generation>=0),
  token_version bigint NOT NULL DEFAULT 0 CHECK (token_version>=0),
  credential_ciphertext bytea,
  credential_nonce bytea CHECK (octet_length(credential_nonce)=12),
  credential_expires_at bigint,
  refresh_claim uuid,
  refresh_deadline bigint,
  refresh_dispatched boolean NOT NULL DEFAULT false,
  auth_sequence bigint NOT NULL DEFAULT 0 CHECK (auth_sequence>=0),
  selection_version bigint NOT NULL DEFAULT 0 CHECK (selection_version>=0),
  booking_calendar text,
  booking_label text,
  blocking_calendars jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(blocking_calendars)='array' AND jsonb_array_length(blocking_calendars)<=100),
  current_probe_id uuid,
  permission_checked_at bigint,
  capability_checked_at bigint,
  notice text,
  CHECK ((credential_ciphertext IS NULL)=(credential_nonce IS NULL)),
  CHECK ((refresh_claim IS NULL)=(refresh_deadline IS NULL)),
  CHECK (NOT refresh_dispatched OR refresh_claim IS NOT NULL),
  CHECK (status<>'connected' OR (credential_ciphertext IS NOT NULL AND credential_expires_at IS NOT NULL)),
  CHECK ((booking_calendar IS NULL)=(booking_label IS NULL)),
  CHECK (capability_checked_at IS NULL OR permission_checked_at IS NOT NULL)
);
INSERT INTO google_connection(id,deployment_marker) VALUES(1,md5(random()::text || clock_timestamp()::text));
CREATE TABLE google_auth_attempts (
  id uuid PRIMARY KEY,
  state_hash bytea NOT NULL UNIQUE CHECK (octet_length(state_hash)=32),
  session_hash bytea NOT NULL CHECK (octet_length(session_hash)=32),
  generation bigint NOT NULL,
  sequence bigint NOT NULL UNIQUE,
  config_fingerprint bytea NOT NULL,
  verifier_ciphertext bytea,
  verifier_nonce bytea CHECK (octet_length(verifier_nonce)=12),
  issued_at bigint NOT NULL,
  expires_at bigint NOT NULL CHECK (expires_at>issued_at),
  outcome text NOT NULL DEFAULT 'pending' CHECK (outcome IN ('pending','consumed','superseded','denied','failed','connected')),
  CHECK ((verifier_ciphertext IS NULL)=(verifier_nonce IS NULL)),
  CHECK ((outcome='pending')=(verifier_ciphertext IS NOT NULL))
);
CREATE INDEX google_auth_issued ON google_auth_attempts(issued_at DESC);
-- No cascading session FK: logout must never erase authorization rate history.
CREATE TABLE google_probes (
  id uuid PRIMARY KEY,
  generation bigint NOT NULL,
  selection_version bigint NOT NULL,
  calendar_id text NOT NULL,
  calendar_label text NOT NULL,
  event_id text NOT NULL CHECK (event_id ~ '^[0-9a-f]{32}$'),
  conference_request_id text NOT NULL UNIQUE,
  deployment_marker text NOT NULL,
  probe_marker text NOT NULL UNIQUE,
  started_at bigint NOT NULL,
  event_start bigint NOT NULL,
  phase text NOT NULL DEFAULT 'prepared' CHECK (phase IN ('prepared','create_committed','observing','cleanup','complete','attention')),
  create_committed_at bigint,
  create_evidence boolean NOT NULL DEFAULT false,
  own_verified boolean NOT NULL DEFAULT false,
  event_permission boolean NOT NULL DEFAULT false,
  conference_outcome text NOT NULL DEFAULT 'pending' CHECK (conference_outcome IN ('pending','success','failed')),
  cleanup_outcome text NOT NULL DEFAULT 'pending' CHECK (cleanup_outcome IN ('pending','deleted','unresolved','not_created')),
  reason text NOT NULL DEFAULT 'queued',
  claim uuid,
  claim_deadline bigint,
  due_at bigint NOT NULL,
  observations integer NOT NULL DEFAULT 0 CHECK (observations BETWEEN 0 AND 12),
  observation_deadline bigint,
  cleanup_calls integer NOT NULL DEFAULT 0 CHECK (cleanup_calls BETWEEN 0 AND 12),
  cleanup_deadline bigint,
  cleanup_generation bigint,
  cleanup_only boolean NOT NULL DEFAULT false,
  delete_auth_attempted boolean NOT NULL DEFAULT false,
  last_cleanup_request bigint,
  checked_at bigint,
  UNIQUE(calendar_id,event_id),
  CHECK ((claim IS NULL)=(claim_deadline IS NULL)),
  CHECK (phase NOT IN ('create_committed','observing','cleanup') OR create_committed_at IS NOT NULL),
  CHECK (phase<>'prepared' OR create_committed_at IS NULL),
  CHECK (cleanup_outcome<>'deleted' OR create_committed_at IS NOT NULL),
  CHECK (cleanup_calls=0 OR cleanup_deadline IS NOT NULL),
  CHECK (NOT event_permission OR (create_evidence AND own_verified AND cleanup_outcome='deleted'))
);
CREATE INDEX google_probe_due ON google_probes(due_at) WHERE phase NOT IN ('complete','attention');
CREATE INDEX google_probe_history ON google_probes(started_at DESC);
CREATE INDEX google_probe_attention ON google_probes(started_at DESC) WHERE cleanup_outcome='unresolved';
ALTER TABLE google_connection ADD CONSTRAINT google_current_probe FOREIGN KEY(current_probe_id) REFERENCES google_probes(id);
